// Helper: Match pure greetings, pleasantries, thanks, and acknowledgements naturally
function getExactConversationalReply(text: string): string | null {
  if (!text) return null;
  const normalized = normalizeArabicText(text);

  // 1. Social "How are you?" ("كيف حالك؟" -> "الحمدلله بخير 🤍 كيف أقدر أساعدك؟")
  if (
    /^(كيف حالك|كيفك|كيف الحال|كيفك اليوم|شخبارك|شلونك|عساك بخير|عساكم بخير|اخبارك|أخبارك|كيف امورك|كيف أمورك|كيف صحتك|how are you|how are you\?)[\s.!?؟]*$/i.test(
      normalized
    )
  ) {
    return 'الحمدلله بخير 🤍 كيف أقدر أساعدك؟';
  }

  // 2. Status / Confirmation ("تمام" / "الحمدلله" -> respond naturally without a formal sales pitch)
  if (
    /^(تمام|الحمدلله|الحمد لله|كويس|طيب|اوكي|أوكي|اوك|أوك|ماشي|حلو|واضح|ممتاز|بخير|تمام الحمدلله|تمام الحمد لله|الحمدلله بخير|ok|okay)[\s.!]*$/i.test(
      normalized
    )
  ) {
    return 'دوم يا رب 🤍 إذا عندك أي استفسار آخر أو تحب تعرف أي تفاصيل، أنا في الخدمة.';
  }

  // 3. Pure Salam ("السلام عليكم" -> "وعليكم السلام 🤍")
  if (
    /^(السلام عليكم ورحمة الله وبركاته|السلام عليكم ورحمة الله|السلام عليكم|سلام عليكم|سلامي|وعليكم السلام)[\s.!]*$/i.test(
      normalized
    )
  ) {
    return 'وعليكم السلام 🤍';
  }

  // 4. Pure Marhaba ("مرحبا" -> "يا ألف أهلاً وسهلاً 🤍✨")
  if (/^(مرحبا|مرحباً|مرحبتين|مراحب|مرحبا بك|مرحبا بكم)[\s.!]*$/i.test(normalized)) {
    return 'يا ألف أهلاً وسهلاً 🤍✨';
  }

  // 5. Pure Ahlan ("أهلا" -> "أهلين 🤍")
  if (/^(اهلا|أهلا|أهلاً|اهلين|أهلين|هلا|يا هلا|هلا وغلا|اهلاً وسهلاً|أهلاً وسهلاً)[\s.!]*$/i.test(normalized)) {
    return 'أهلين 🤍';
  }

  // 6. Presence / "Alo" ("الو" / "ألو")
  if (/^(الو|ألو|موجود|معي|تسمعني)[\s.!?؟]*$/i.test(normalized)) {
    return 'أهلاً بك 🤍 معك، تفضل كيف أقدر أساعدك؟';
  }

  // 7. Pure Morning
  if (/^(صباح الخير|صباح النور|صباح الورد|صباحكم خير)[\s.!]*$/i.test(normalized)) {
    return 'صباح النور والسرور 🤍 يومك مبارك وطيب.';
  }

  // 8. Pure Evening
  if (/^(مساء الخير|مساء النور|مساء الورد|مساءكم خير)[\s.!]*$/i.test(normalized)) {
    return 'مساء النور والبهجة 🤍 يا ألف مرحباً بك.';
  }

  // 9. Gratitude / Thanks ("شكراً" -> respond naturally to the thanks)
  if (
    /^(شكرا|شكراً|مشكور|مشكورة|مشكورين|تسلم|تسلمي|تسلموا|يعطيك العافية|الله يعطيك العافية|جزاك الله خير|جزاكم الله خيرا|الف شكر|شكرا جزيلا|thx|thanks|thank you)[\s.!]*$/i.test(
      normalized
    )
  ) {
    return 'العفو، في خدمتكم دائماً 🤍 وأهلاً وسهلاً بكم في أي وقت.';
  }

  // 10. Acknowledgment ("العفو" -> respond naturally without restarting full intro)
  if (/^(العفو|عفوا|عفواً|لا شكر على واجب|حياك|حياكم|حياكم الله|على الرحب والسعة|على الرحب)[\s.!]*$/i.test(normalized)) {
    return 'حياك الله 🤍 على الرحب والسعة.';
  }

  // 11. Farewell
  if (/^(مع السلامة|باي|في أمان الله|ودعتك الله|إلى اللقاء|مع السلامه|bye)[\s.!]*$/i.test(normalized)) {
    return 'في أمان الله وحفظه 🤍 وأهلاً وسهلاً بك في أي وقت.';
  }

  // 12. English greetings
  if (/^(hi|hello|hey|good morning|good evening)[\s.!]*$/i.test(normalized)) {
    return 'يا ألف أهلاً وسهلاً 🤍✨ Welcome to Ar-Rasheed Modern Schools.';
  }

  return null;
}

// Helper: Provide a natural greeting prefix ONLY when a message explicitly contains a greeting
function getGreetingPrefix(normalized: string, isOngoing: boolean = false): string {
  if (normalized.includes('السلام عليكم') || normalized.includes('سلام عليكم')) {
    return 'وعليكم السلام ورحمة الله 🤍 ';
  }
  if (normalized.includes('مرحبا') || normalized.includes('مرحبتين') || normalized.includes('مراحب')) {
    return 'يا ألف أهلاً وسهلاً 🤍 ';
  }
  if (normalized.includes('صباح الخير')) {
    return 'صباح النور والسرور 🤍 ';
  }
  if (normalized.includes('مساء الخير')) {
    return 'مساء النور والبهجة 🤍 ';
  }
  if (normalized.includes('اهلا') || normalized.includes('اهلين') || normalized.includes('هلا')) {
    return 'أهلين وسهلاً بك 🤍 ';
  }
  // During ongoing conversation or direct questions, do not repeat greeting prefixes
  return '';
}

