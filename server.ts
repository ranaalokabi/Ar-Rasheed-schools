// In-memory model cooldown tracking for rate-limited / quota-exhausted models
const modelExhaustedUntil: Record<string, number> = {
  // Pre-cool down gemini-3.8-flash if daily token limit (25M) is exceeded
  'gemini-3.8-flash': Date.now() + 86400000,
  'gemini-flash-latest': Date.now() + 86400000,
};

function isModelCoolingDown(model: string): boolean {
  const until = modelExhaustedUntil[model];
  return typeof until === 'number' && Date.now() < until;
}

function markModelExhausted(model: string, retryDelaySec = 60) {
  const delayMs = Math.max(retryDelaySec * 1000, 60000);
  const expiry = Date.now() + delayMs;
  modelExhaustedUntil[model] = expiry;
  // gemini-3.8-flash and gemini-flash-latest share the same quota bucket
  if (model === 'gemini-3.8-flash' || model === 'gemini-flash-latest') {
    modelExhaustedUntil['gemini-3.8-flash'] = expiry;
    modelExhaustedUntil['gemini-flash-latest'] = expiry;
  }
}

// Resilient Gemini generateContent with fallback models and realistic timeout
async function generateGeminiChat(
  client: GoogleGenAI,
  contents: any[],
  timeoutMs = 12000
): Promise<string | null> {
  // Prioritize high-efficiency gemini-3.1-flash-lite with generous quota, followed by flash aliases
  const models = ['gemini-3.1-flash-lite', 'gemini-flash-latest'];

  for (const model of models) {
    if (isModelCoolingDown(model)) {
      continue;
    }

    try {
      const config: any = {
        systemInstruction: SYSTEM_INSTRUCTION,
        temperature: 0.65,
      };

      if (model.startsWith('gemini-3')) {
        config.thinkingConfig = { thinkingLevel: ThinkingLevel.LOW };
      }

      const geminiPromise = client.models.generateContent({
        model,
        contents,
        config,
      });

      const timeoutPromise = new Promise((_, reject) =>
        setTimeout(() => reject(new Error(`Gemini API timeout (${model})`)), timeoutMs)
      );

      const geminiResponse: any = await Promise.race([geminiPromise, timeoutPromise]);
      const replyText = geminiResponse?.text;
      if (replyText && replyText.trim()) {
        return replyText.trim();
      }
    } catch (err: any) {
      const errMsg = err?.message || String(err);
      const isQuotaExhausted =
        err?.status === 'RESOURCE_EXHAUSTED' ||
        err?.code === 429 ||
        errMsg.includes('429') ||
        errMsg.includes('Quota exceeded') ||
        errMsg.includes('RESOURCE_EXHAUSTED') ||
        errMsg.includes('resource_exhausted') ||
        errMsg.includes('exceeded your current quota');

      if (isQuotaExhausted) {
        let delaySec = 300;
        const match = errMsg.match(/retry in ([\d.]+)s/i) || errMsg.match(/retryDelay":"(\d+)s/i);
        if (match && match[1]) {
          delaySec = Math.ceil(parseFloat(match[1])) + 2;
        }
        if (
          errMsg.includes('PerDay') ||
          errMsg.includes('free_tier_requests') ||
          errMsg.includes('tokens_per_model_per_user') ||
          errMsg.includes('exceeded your current quota')
        ) {
          delaySec = 86400; // 24 hours cooldown for daily token/quota exhaustion
        }
        markModelExhausted(model, delaySec);
      }
      // Continue to next available model or knowledge fallback cleanly without noisy error dumps
    }
  }

  return null;
}

