// Serve frontend with static dist files in production/Cloud Run, or Vite middleware in dev
async function startServer() {
  const distPath = path.resolve(__dirname, 'dist');
  const distIndexExists = fs.existsSync(path.resolve(distPath, 'index.html'));
  const isProduction =
    process.env.NODE_ENV === 'production' ||
    Boolean(process.env.K_SERVICE) ||
    distIndexExists;

  if (isProduction && distIndexExists) {
    app.use(express.static(distPath));
    app.get('*', (req, res) => {
      res.sendFile(path.resolve(distPath, 'index.html'));
    });
  } else {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Ar-Rasheed Modern Schools Receptionist Server running on http://0.0.0.0:${PORT}`);
  });
}

