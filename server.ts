// Admin Authorization Middleware
const ADMIN_SECRET_TOKEN = 'rms_admin_token_2026';

function requireAdminAuth(req: express.Request, res: express.Response, next: express.NextFunction) {
  const token = req.headers['x-admin-token'] || req.headers['authorization']?.replace('Bearer ', '');
  if (token === ADMIN_SECRET_TOKEN || req.query.token === ADMIN_SECRET_TOKEN) {
    return next();
  }
  return res.status(401).json({ error: 'Unauthorized: Admin authentication required' });
}

// GET /api/admin/conversations - Admin list with search, filter, and analytics
app.get('/api/admin/conversations', requireAdminAuth, async (req, res) => {
  try {
    const { search, status, topic, sort } = req.query;
    let list = await getStoredConversations();

    // 1. Calculate Analytics on unfiltered list
    const todayStr = new Date().toISOString().slice(0, 10);
    const totalConversations = list.length;
    const todayConversations = list.filter((c) => c.createdAt && c.createdAt.startsWith(todayStr)).length;
    const needsReviewCount = list.filter((c) => !c.reviewStatus || c.reviewStatus === 'unreviewed').length;
    const correctCount = list.filter((c) => c.reviewStatus === 'correct').length;
    const needsImprovementCount = list.filter((c) => c.reviewStatus === 'needs_improvement').length;
    const incorrectCount = list.filter((c) => c.reviewStatus === 'incorrect').length;
    const notUnderstoodCount = list.filter((c) => c.reviewStatus === 'not_understood').length;

    // Topic stats
    const topicCounts: Record<string, number> = {};
    list.forEach((c) => {
      (c.detectedTopics || ['general']).forEach((t) => {
        topicCounts[t] = (topicCounts[t] || 0) + 1;
      });
    });

    const topicStats = Object.entries(topicCounts)
      .map(([key, count]) => ({
        topicKey: key,
        topicLabelAr: TOPIC_ARABIC_NAMES[key] || key,
        count,
        percentage: totalConversations > 0 ? Math.round((count / totalConversations) * 100) : 0,
      }))
      .sort((a, b) => b.count - a.count);

    // Frequent Questions (filtering out abusive or inappropriate queries)
    const questionMap: Record<string, { question: string; topicKey: string; count: number; lastTime: string }> = {};
    list.forEach((c) => {
      if (c.flaggedAsInappropriate) return;
      c.messages
        .filter((m) => m.role === 'user')
        .forEach((m) => {
          const cleanQ = m.content.trim();
          if (cleanQ.length < 3 || detectInappropriateContent(cleanQ)) return;
          const key = cleanQ.toLowerCase().replace(/[\u064B-\u065F\u0670?!؟.]/g, '').trim();
          if (!questionMap[key]) {
            questionMap[key] = {
              question: cleanQ,
              topicKey: c.detectedTopics?.[0] || 'general',
              count: 1,
              lastTime: m.timestamp || '',
            };
          } else {
            questionMap[key].count += 1;
          }
        });
    });

    const frequentQuestions = Object.values(questionMap)
      .sort((a, b) => b.count - a.count)
      .slice(0, 10)
      .map((item) => ({
        question: item.question,
        topicLabelAr: TOPIC_ARABIC_NAMES[item.topicKey] || item.topicKey,
        frequency: item.count,
        lastAskedTime: item.lastTime,
      }));

    // 2. Filter list for view
    let filtered = [...list];

    if (search && typeof search === 'string') {
      const q = search.toLowerCase().trim();
      filtered = filtered.filter(
        (c) =>
          c.anonymousId.toLowerCase().includes(q) ||
          c.lastQuestion.toLowerCase().includes(q) ||
          (c.supervisorNotes && c.supervisorNotes.toLowerCase().includes(q)) ||
          c.messages.some((m) => m.content.toLowerCase().includes(q))
      );
    }

    if (status && status !== 'all' && typeof status === 'string') {
      filtered = filtered.filter((c) => c.reviewStatus === status);
    }

    if (topic && topic !== 'all' && typeof topic === 'string') {
      filtered = filtered.filter((c) => c.detectedTopics && c.detectedTopics.includes(topic));
    }

    // 3. Sort
    if (sort === 'oldest') {
      filtered.sort((a, b) => new Date(a.createdAt).getTime() - new Date(b.createdAt).getTime());
    } else if (sort === 'needs_review') {
      filtered.sort((a, b) => {
        const aNeeds = a.reviewStatus === 'unreviewed' ? 1 : 0;
        const bNeeds = b.reviewStatus === 'unreviewed' ? 1 : 0;
        return bNeeds - aNeeds;
      });
    } else {
      // newest
      filtered.sort(
        (a, b) => new Date(b.updatedAt || b.createdAt).getTime() - new Date(a.updatedAt || a.createdAt).getTime()
      );
    }

    return res.json({
      conversations: filtered,
      analytics: {
        totalConversations,
        todayConversations,
        needsReviewCount,
        correctCount,
        needsImprovementCount,
        incorrectCount,
        notUnderstoodCount,
        topicStats,
        frequentQuestions,
      },
    });
  } catch (err: any) {
    console.error('Fetch conversations error:', err);
    return res.status(500).json({ error: 'Failed to retrieve conversations' });
  }
});

