app.post('/api/tts', async (req, res) => {
  try {
    const { text } = req.body;
    if (!text) {
      return res.status(400).json({ error: 'Text is required' });
    }

    const aiClient = getAiClient();
    if (!aiClient) {
      return res.json({ audioBase64: null, note: 'Web Speech fallback available' });
    }

    try {
      const ttsPromise = aiClient.models.generateContent({
        model: 'gemini-3.8-flash-lite-tts',
        contents: [
          {
            role: 'user',
            parts: [
              {
                text: text.slice(0, 700),
                speechMetadata: {
                  style: 'Warm, refined, friendly female school receptionist speaking clear Arabic',
                },
              },
            ],
          },
        ],
        config: {
          responseModalities: ['AUDIO'],
          speechConfig: {
            voiceConfig: {
              prebuiltVoiceConfig: { voiceName: 'Kore' },
            },
          },
        },
      });

      const timeoutPromise = new Promise((_, reject) =>
        setTimeout(() => reject(new Error('TTS timeout')), 15000)
      );

      const ttsResponse: any = await Promise.race([ttsPromise, timeoutPromise]);
      const part = ttsResponse?.candidates?.[0]?.content?.parts?.[0];
      const audioBase64 = part?.inlineData?.data;
      const mimeType = part?.inlineData?.mimeType || 'audio/mp3';
      if (audioBase64) {
        return res.json({ audioBase64, mimeType });
      }
    } catch (ttsErr: any) {
      // client speech fallback will be used smoothly without console spam
    }

    return res.json({ audioBase64: null });
  } catch (err: any) {
    return res.json({ audioBase64: null, note: 'Web Speech fallback available' });
  }
});

